'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const evidence = require('../backend/tennisPlayerEvidence');
const intelligence = require('../backend/tennisMatchupIntelligence');
const registry = require('../backend/tennisPatchRegistry');
const root = path.resolve(__dirname, '..');
assert.ok(Number(registry.TENNIS_CURRENT_PATCH_VERSION) >= 12);
assert.strictEqual(registry.TENNIS_PATCH_REGISTRY_VERSION, `TENNIS_PATCH_REGISTRY_V${registry.TENNIS_CURRENT_PATCH_VERSION}`);
assert.ok(registry.PATCHES.some(p => p.version === '11' && String(p.status).startsWith('ACTIVE')));
assert.ok(registry.PATCHES.some(p => p.version === '12' && String(p.status).startsWith('ACTIVE')));
const status = evidence.init(path.join(root,'backend/sackmann_data'), { force:true });
assert.ok(status.matchCount > 20000 && status.playerCount > 1000);
assert.strictEqual(status.networkUsed, false);
assert.strictEqual(status.temporalLeakageGuard, true);
const legacyApiEvidence = evidence.buildPlayerEvidence('Jannik Sinner','Grass','2026-07-10T12:00:00Z',{dataDir:path.join(root,'backend/sackmann_data')});
assert.ok(legacyApiEvidence.sampleTotal > 0);
assert.ok(legacyApiEvidence.asOfAt.startsWith('2026-07-10'));
const matchup = evidence.buildMatchupEvidence('Jannik Sinner','Novak Djokovic','Grass','2026-07-10T12:00:00Z',{dataDir:path.join(root,'backend/sackmann_data')});
assert.ok(matchup.p1.sampleTotal > 0 && matchup.p2.sampleTotal > 0);
assert.ok(matchup.asOfAt.startsWith('2026-07-10'));
const unknown = evidence.buildMatchupEvidence('Unknown Player A','Unknown Player B','Hard','2026-07-10T12:00:00Z',{dataDir:path.join(root,'backend/sackmann_data')});
assert.strictEqual(unknown.status, 'INSUFFICIENT_EVIDENCE');
const challenger = evidence.buildChallengerPrediction({player1:'Jannik Sinner',player2:'Novak Djokovic',surface:'Grass',asOf:'2026-07-10T12:00:00Z',marketProbabilityP1:65,marketProbabilityP2:35,productionProbabilityP1:68,productionProbabilityP2:32,prediction:'1',marketType:'h2h',matchup});
assert.strictEqual(challenger.mode, intelligence.MODE);
assert.ok(!Object.prototype.hasOwnProperty.call(challenger,'stake'));
const db = new DatabaseSync(':memory:');
const persisted = intelligence.persistMatchupIntelligenceForBet(db,{id:1,home_team:'Jannik Sinner',away_team:'Novak Djokovic',match_date:'2026-07-10T12:00:00Z',surface:'Grass',prediction:'1',estimated_prob:68,market_implied_prob:65,market_type:'h2h',reference_odd1:1.5,reference_odd2:3},{home:'Jannik Sinner',away:'Novak Djokovic',date:'2026-07-10T12:00:00Z',surface:'Grass',prediction:'1',estimatedProb:68,marketImpliedProbability:65,marketType:'h2h',referenceOdd1:1.5,referenceOdd2:3},{snapshotId:'STANDALONE12',dataDir:path.join(root,'backend/sackmann_data')});
assert.ok(persisted.persisted);
assert.strictEqual(intelligence.getIntelligenceHealth(db).healthy, true);
assert.throws(()=>db.prepare('UPDATE tennis_matchup_feature_snapshots SET matchup_label=?').run('X'),/PATCH12_MATCHUP_FEATURES_IMMUTABLE/);
const server=fs.readFileSync(path.join(root,'backend/server.tennis.js'),'utf8');
const app=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
assert.ok(server.includes("operation.error('SNAPSHOT_FAILED'"));
assert.ok(server.includes("patch12Event: 'PLAYER_MATCHUP_INTELLIGENCE_FAILED'"));
assert.ok(server.includes("router.get('/player-matchup-intelligence'"));
assert.ok(server.includes('buildPatch12PlayerMatchupIntelligence'));
assert.ok(app.includes('loadTennisMatchupIntelligence'));
assert.ok(html.includes('tennisMatchupIntelligencePanel') && html.includes(`Patch 1–${registry.TENNIS_CURRENT_PATCH_VERSION}`));
const patch11Test=fs.readFileSync(path.join(root,'backend/tests/patch11TennisForwardCaptureHealthAndSafeSupport.test.js'),'utf8');
assert.ok(patch11Test.includes('Patch 1–${registry.TENNIS_CURRENT_PATCH_VERSION}'));
assert.strictEqual(fs.readFileSync(path.join(root,'public/app.js'),'utf8'),fs.readFileSync(path.join(root,'backend/public/app.js'),'utf8'));
assert.strictEqual(fs.readFileSync(path.join(root,'public/index.html'),'utf8'),fs.readFileSync(path.join(root,'backend/public/index.html'),'utf8'));
console.log(`PATCH12 standalone PASS: ${status.matchCount} local matches, ${status.playerCount} players, as-of-safe evidence, immutable matchup/challenger and UI linkage.`);
