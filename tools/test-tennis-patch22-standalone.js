'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(process.argv[2]||path.join(__dirname,'..'));
const readiness=require(path.join(root,'backend/tennisTourDataReadiness'));
const evidence=require(path.join(root,'backend/tennisPlayerEvidence'));
const registry=require(path.join(root,'backend/tennisPatchRegistry'));
const report=readiness.buildTargetReadiness({dataDir:path.join(root,'backend/sackmann_data'),projectRoot:root,now:new Date('2026-07-20T08:00:00.000Z')});
assert.strictEqual(registry.TENNIS_CURRENT_PATCH_VERSION,'22');
assert.strictEqual(report.status,'MIXED_CURRENT_STALE');
assert.strictEqual(report.sourceFreshnessNotMasked,true);
assert.strictEqual(report.targets.find(x=>x.targetId==='ATP_MAIN').status,'CURRENT');
assert.strictEqual(report.targets.find(x=>x.targetId==='ATP_QUAL_CHALL').status,'CURRENT');
assert.strictEqual(report.targets.find(x=>x.targetId==='WTA_MAIN').status,'STALE');
assert.strictEqual(readiness.resolveTargetId({tour:'WTA'}),'WTA_MAIN');
assert.strictEqual(readiness.resolveTargetId({tour:'ATP',tournamentLevel:'Challenger'}),'ATP_QUAL_CHALL');
const separation=readiness.resolveEvidenceReadiness({tour:'ATP',activityDays:60},{report});
assert.strictEqual(separation.sourceFreshnessStatus,'CURRENT');
assert.strictEqual(separation.activityStatus,'LONG_ABSENCE');
assert.strictEqual(separation.sourceFreshnessSeparateFromPlayerActivity,true);
const atp=evidence.buildPlayerEvidence('Jannik Sinner','Opponent','Hard','2026-07-20T08:00:00.000Z',{dataDir:path.join(root,'backend/sackmann_data'),tour:'ATP'});
const wta=evidence.buildPlayerEvidence('Coco Gauff','Opponent','Hard','2026-07-20T08:00:00.000Z',{dataDir:path.join(root,'backend/sackmann_data'),tour:'WTA'});
assert.strictEqual(atp.sourceTargetId,'ATP_MAIN');
assert.strictEqual(atp.sourceFreshnessStatus,'CURRENT');
assert.strictEqual(wta.sourceTargetId,'WTA_MAIN');
assert.strictEqual(wta.sourceFreshnessStatus,'STALE');
assert.strictEqual(atp.sourceFreshnessSeparateFromPlayerActivity,true);
assert.strictEqual(wta.sourceFreshnessSeparateFromPlayerActivity,true);
const server=fs.readFileSync(path.join(root,'backend/server.tennis.js'),'utf8');
const app=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
assert(server.includes("router.get('/tour-data-readiness'"));
assert(app.includes('loadTennisTourDataReadiness'));
assert(html.includes('Patch 1–22'));
assert(html.includes('Freschezza per circuito'));
assert.strictEqual(report.authority.productionProbability,false);
assert.strictEqual(report.authority.qualityGate,false);
assert.strictEqual(report.authority.stake,false);
console.log(`PATCH22 standalone PASS: ATP current, WTA stale, source freshness unmasked, activity separated, UI/backend linked and no operational authority.`);
