#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');
const pkg = JSON.parse(read('package.json'));
const tennisRegistry = require(path.join(root, 'backend', 'tennisPatchRegistry.js'));
const globalRegistry = require(path.join(root, 'backend', 'calcioPatchRegistry.js'));
const lifecycle = require(path.join(root, 'backend', 'tennisForwardLifecycle.js'));
const ledger = require(path.join(root, 'backend', 'oddsApiUsageLedger.js'));
const server = read('backend/server.tennis.js');
const app = read('public/app.js');
const backendApp = read('backend/public/app.js');
const index = read('public/index.html');
const backendIndex = read('backend/public/index.html');
const checks = [];
function check(name, ok) { checks.push({ name, ok: Boolean(ok) }); }
check('registry Tennis 28 preservato', String(tennisRegistry.TENNIS_CURRENT_PATCH_VERSION) === '28');
check('registry globale 37 preservato', String(globalRegistry.CALCIO_CURRENT_PATCH_VERSION) === '37');
check('package 21.13.0 preservato', pkg.version === '21.13.0');
check('lifecycle V2 Patch28 R1 attivo', lifecycle.TENNIS_FORWARD_LIFECYCLE_VERSION === 'TENNIS_FORWARD_LIFECYCLE_V2_PATCH28_R1');
check('PROPOSED ha stato evidenza pending', lifecycle.deriveLifecycleState({status:'PENDING',settlement_contract_status:'PROPOSED'}, {snapshot_status:'VALID_PREMATCH'}, {match:true}, {valid:true}) === 'SETTLEMENT_EVIDENCE_PENDING');
check('CONFLICT resta review', lifecycle.deriveLifecycleState({status:'PENDING',settlement_contract_status:'CONFLICT'}, {snapshot_status:'VALID_PREMATCH'}, {match:true}, {valid:true}) === 'REVIEW_REQUIRED');
check('ledger esporta writer resiliente', typeof ledger.writeJsonAtomicResilient === 'function');
check('server usa telemetria non bloccante', server.includes('ODDS_API_LEDGER_NON_BLOCKING') && server.includes("safeOddsUsageTelemetry('recordOddsApiNetworkAttempt'"));
check('risposta provider non dipende dal ledger', server.includes("safeOddsUsageTelemetry('recordOddsApiResponse'") && server.includes('return response.data;'));
const lifecycleLoader=(app.match(/async function loadTennisForwardLifecycle\(\) \{[\s\S]*?\n\}/)||[''])[0];
check('frontend non interpreta success false come endpoint assente', lifecycleLoader.includes('if (!response.ok)') && !lifecycleLoader.includes('payload.success === false'));
check('frontend distingue drift da indisponibilità', app.includes('Watchdog disponibile: rilevati') && app.includes("title: 'Lifecycle Tennis da riallineare'"));
check('frontend espone evidenza settlement in verifica', app.includes('Evidenza settlement in verifica'));
check('frontend copie sincronizzate', app === backendApp);
check('cache buster R1 attivo', index.includes('patch28-r1-lifecycle-atp-ledger-recovery'));
check('index copie sincronizzate', index === backendIndex);
check('script reconcile presente', fs.existsSync(path.join(root,'backend','reconcileTennisPatch28R1.js')));
check('script verifica R1 presente', Boolean(pkg.scripts?.['verify:tennis:patch28:r1']));
check('nessuna modifica autorità probabilità', !server.includes('PATCH28_R1_PROBABILITY_OVERRIDE'));
check('nessuna nuova chiamata Odds API', !server.includes('PATCH28_R1_NEW_ODDS_API_CALL'));
const failed = checks.filter(x => !x.ok);
const out = { success: failed.length === 0, patch: 'TENNIS_PATCH_28_R1_LIFECYCLE_AVAILABILITY_ATP_LEDGER_RECOVERY', checks: checks.length, passed: checks.length - failed.length, failed: failed.length, results: checks };
console.log(JSON.stringify(out, null, 2));
process.exitCode = out.success ? 0 : 1;
