'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const capture = require('../backend/tennisForwardCaptureHealth');
const registry = require('../backend/tennisPatchRegistry');
const support = require('./create-tennis-safe-support-bundle');
assert.ok(Number(registry.TENNIS_CURRENT_PATCH_VERSION) >= 11);
assert.strictEqual(registry.TENNIS_PATCH_REGISTRY_VERSION, `TENNIS_PATCH_REGISTRY_V${registry.TENNIS_CURRENT_PATCH_VERSION}`);
assert.ok(registry.PATCHES.some(p => p.version === '11' && String(p.status).startsWith('ACTIVE')));
assert.ok(registry.PATCHES.some(p => p.version === '10'));
const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE ai_forward_test (id INTEGER PRIMARY KEY, sport_type TEXT, bet_type TEXT, strategy_tag TEXT, league TEXT, quality_decision_at TEXT, quality_final_version TEXT); CREATE TABLE tennis_prediction_snapshots (bet_id INTEGER,is_calibration_anchor INTEGER);`);
const empty = capture.scanForwardCaptureHealth(db);
assert.strictEqual(empty.status, capture.CAPTURE_STATUS.NO_FORWARD_DATA);
assert.ok(support.shouldExclude('backend/.env'));
assert.ok(support.shouldExclude('node_modules/a.js'));
assert.ok(support.shouldExclude('backend/backups/legacy.js'));
assert.ok(!support.shouldExclude('backend/server.tennis.js'));
const server = fs.readFileSync(path.resolve(__dirname, '../backend/server.tennis.js'), 'utf8');
const app = fs.readFileSync(path.resolve(__dirname, '../public/app.js'), 'utf8');
const html = fs.readFileSync(path.resolve(__dirname, '../public/index.html'), 'utf8');
assert.ok(server.includes("router.get('/forward-capture-health'"));
assert.ok(app.includes('loadTennisForwardCaptureHealth'));
assert.ok(html.includes('tennisForwardCapturePanel'));
console.log('PATCH11 standalone audit PASS: SLA capture read-only, Quality decision coherence, compact UI and secure support export.');
